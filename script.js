const menuToggle = document.querySelector(".menu-toggle");
const navLinks = document.querySelector(".nav-links");
const langToggle = document.querySelector("[data-lang-toggle]");
const themeToggle = document.querySelector("[data-theme-toggle]");
const translatable = document.querySelectorAll("[data-i18n]");
const form = document.querySelector(".contact-form");

let currentLang = localStorage.getItem("afaq-jood-lang") || "ar";
let currentTheme = localStorage.getItem("afaq-jood-theme") || "light";

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("en", lang === "en");
  translatable.forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = dictionary[lang][key] || node.textContent;
  });
  langToggle.textContent = lang === "ar" ? "EN" : "AR";
  localStorage.setItem("afaq-jood-lang", lang);
}

function setTheme(theme) {
  currentTheme = theme;
  document.body.classList.toggle("dark", theme === "dark");
  themeToggle.textContent = theme === "dark" ? "☼" : "◐";
  localStorage.setItem("afaq-jood-theme", theme);
}

menuToggle.addEventListener("click", () => {
  const isOpen = navLinks.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});

navLinks.addEventListener("click", (event) => {
  if (event.target.matches("a")) {
    navLinks.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  }
});

langToggle.addEventListener("click", () => {
  setLanguage(currentLang === "ar" ? "en" : "ar");
});

themeToggle.addEventListener("click", () => {
  setTheme(currentTheme === "dark" ? "light" : "dark");
});

if (form) {
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const message =
      currentLang === "ar"
        ? "تم تجهيز الطلب تجريبيًا. يمكننا ربط النموذج بالبريد أو واتساب في الخطوة التالية."
        : "Demo request prepared. We can connect the form to email or WhatsApp in the next step.";
    alert(message);
    form.reset();
  });
}

const sections = [...document.querySelectorAll("main section[id]")];
const links = [...document.querySelectorAll(".nav-links a")];

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        links.forEach((link) => {
          link.classList.toggle("active", link.getAttribute("href") === `#${entry.target.id}`);
        });
      }
    });
  },
  { rootMargin: "-35% 0px -55% 0px" },
);

sections.forEach((section) => observer.observe(section));

const pageName = window.location.pathname.split("/").pop() || "index.html";
links.forEach((link) => {
  const linkName = link.getAttribute("href").split("#")[0];
  link.classList.toggle("active", linkName === pageName);
});

setLanguage(currentLang);
setTheme(currentTheme);
